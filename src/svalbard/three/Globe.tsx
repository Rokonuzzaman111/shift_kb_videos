export const drawLand = (g: CanvasRenderingContext2D, w: number, h: number, polys: Poly[], fill: string, stroke: string, lw: number) => {
  const px = ([lon, lat]: [number, number]) => [((lon + 180) / 360) * w, ((90 - lat) / 180) * h] as const;
  polys.forEach((poly) => {
    g.beginPath();
    poly.forEach((pt, i) => {
      const [x, y] = px(pt);
      if (i === 0) g.moveTo(x, y);
      else g.lineTo(x, y);
    });
    g.closePath();
    g.fillStyle = fill;
    g.fill();
    g.strokeStyle = stroke;
    g.lineWidth = lw;
    g.stroke();
  });
};

export const Globe: React.FC<{ readonly highlight?: number }> = ({ highlight = 0 }) => {
  const { map, emit } = useMemo(() => {
    const W = 4096;
    const H = 2048;
    const base = canvasTex(W, H, (g) => {
      const grad = g.createLinearGradient(0, 0, 0, H);
      grad.addColorStop(0, "#0d2a44");
      grad.addColorStop(0.5, "#061423");
      grad.addColorStop(1, "#0a1e33");
      g.fillStyle = grad;
      g.fillRect(0, 0, W, H);
      // arctic sea ice cap
      const ice = g.createLinearGradient(0, 0, 0, H * 0.09);
      ice.addColorStop(0, "rgba(230,245,255,0.85)");
      ice.addColorStop(1, "rgba(230,245,255,0)");
      g.fillStyle = ice;
      g.fillRect(0, 0, W, H * 0.09);
      g.strokeStyle = "rgba(120,200,255,0.16)";
      g.lineWidth = 2;
      for (let lon = -180; lon <= 180; lon += 15) {
        const x = ((lon + 180) / 360) * W;
        g.beginPath();
        g.moveTo(x, 0);
        g.lineTo(x, H);
        g.stroke();
      }
      for (let lat = -75; lat <= 75; lat += 15) {
        const y = ((90 - lat) / 180) * H;
        g.beginPath();
        g.moveTo(0, y);
        g.lineTo(W, y);
        g.stroke();
      }
      drawLand(g, W, H, LAND, "#1d3a4e", "rgba(130,220,255,0.75)", 3);
      drawLand(g, W, H, SVALBARD, "#e8f6ff", "rgba(180,240,255,1)", 2);
      // snow on high-latitude land
      g.globalCompositeOperation = "source-atop";
      const snow = g.createLinearGradient(0, H * 0.05, 0, H * 0.2);
      snow.addColorStop(0, "rgba(235,248,255,0.9)");
      snow.addColorStop(1, "rgba(235,248,255,0)");
      g.globalCompositeOperation = "source-over";
    });
    const em = canvasTex(W, H, (g) => {
      g.fillStyle = "#000";
      g.fillRect(0, 0, W, H);
      drawLand(g, W, H, SVALBARD, "#5dffb0", "#5dffb0", 6);
    });
    return { map: base, emit: em };
  }, []);
  // Greenland is snow-white in reality: overlay a pale fill
  return (
    <group>
      <mesh rotation={[0, -Math.PI / 2, 0]}>
        <sphereGeometry args={[1, 128, 96]} />
        <meshStandardMaterial map={map} emissiveMap={emit} emissive="#ffffff" emissiveIntensity={0.15 + highlight * 1.6} roughness={0.75} metalness={0.05} />
      </mesh>
      <Atmosphere />
    </group>
  );
};

const Atmosphere: React.FC = () => {
  const mat = useMemo(
    () =>
      new THREE.ShaderMaterial({
        transparent: true,
        depthWrite: false,
        side: THREE.BackSide,
        blending: THREE.AdditiveBlending,
        vertexShader: `varying vec3 vN; varying vec3 vV; void main(){ vec4 mv = modelViewMatrix*vec4(position,1.0); vN = normalize(normalMatrix*normal); vV = normalize(-mv.xyz); gl_Position = projectionMatrix*mv; }`,
        fragmentShader: `varying vec3 vN; varying vec3 vV; void main(){ float f = pow(1.0 - abs(dot(vN, vV)), 2.5); gl_FragColor = vec4(vec3(0.3,0.75,1.0)*f*1.4, f); }`,
      }),
    [],
  );
  return (
    <mesh material={mat} scale={1.12}>
      <sphereGeometry args={[1, 64, 48]} />
    </mesh>
  );
};
